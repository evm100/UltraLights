#!/usr/bin/env python3
"""Generate components/ul_board/src/ul_chip_rules.c from contracts/chips.json.

    python3 firmware/tools/gen_chip_rules.py           write the file
    python3 firmware/tools/gen_chip_rules.py --check   exit 1 if it is stale
"""
import json
import sys
from pathlib import Path

FW = Path(__file__).resolve().parent.parent
CHIPS = FW.parent / "contracts" / "chips.json"
OUT = FW / "components" / "ul_board" / "src" / "ul_chip_rules.c"
ENUM = {"esp32c3": "UL_CHIP_ESP32C3", "esp32c6": "UL_CHIP_ESP32C6"}


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    chips = json.loads(CHIPS.read_text())
    out = [
        "/* GENERATED by firmware/tools/gen_chip_rules.py from contracts/chips.json. Do not edit. */",
        '#include "ul_board_rules.h"',
        "",
        "const ul_chip_rules_t UL_CHIP_RULES[UL_CHIP_COUNT] = {",
    ]
    for key, enum in ENUM.items():
        c = chips[key]
        unusable = {int(k): v for k, v in c["unusable"].items()}
        caution = {int(k): v for k, v in c["caution"].items()}
        lim = c["limits"]
        out.append(f"    [{enum}] = {{")
        out.append(f"        .name = {c_str(c['name'])},")
        out.append(f"        .gpio_max = {c['gpio_max']},")
        out.append(f"        .boot_button = {c['boot_button']},")
        out.append(f"        .max_pwm = {lim['pwm']}, .max_pwm_freqs = {lim['pwm_freqs']}, .max_argb = {lim['argb']},")
        out.append("        .unusable = {")
        for g in sorted(unusable):
            out.append(f"            [{g}] = {c_str(unusable[g])},")
        out.append("        },")
        out.append("        .caution = {")
        for g in sorted(caution):
            out.append(f"            [{g}] = {c_str(caution[g])},")
        out.append("        },")
        out.append("    },")
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is stale: run firmware/tools/gen_chip_rules.py")
        print("chip rules up to date")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT}")
